#!/bin/bash
# 전체 관로 피로도 업데이트 파이프라인 (모든 지역)
# 각 지역별 스크립트를 순서대로 실행합니다.
#
#   run_0520_pipeline.sh  - 0520 지역 (소구역 0243/0461/0470/0480/0490 포함)
#   run_0100_pipeline.sh  - 0100 지역 (사라봉)
#
# 특정 지역만 실행하려면 해당 스크립트를 직접 실행하세요.

set -euo pipefail

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
cd "$SCRIPT_DIR"

ts() { date '+%Y-%m-%d %H:%M:%S'; }

start_time=$(date +%s)

echo "=================================================================="
echo "전체 관로 피로도 업데이트 파이프라인"
echo "시작: $(ts)"
echo "=================================================================="

bash run_0520_pipeline.sh
bash run_0100_pipeline.sh

end_time=$(date +%s)
elapsed=$((end_time - start_time))

echo ""
echo "=================================================================="
echo "전체 파이프라인 완료 | 총 소요 시간: ${elapsed}초"
echo "종료: $(ts)"
echo "=================================================================="
